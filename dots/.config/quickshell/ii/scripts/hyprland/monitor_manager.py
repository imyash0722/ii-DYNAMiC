#!/usr/bin/env python3
import argparse
import json
import os
import re
import subprocess
import sys


def get_hypr_dir():
    return os.path.expanduser("~/.config/hypr")


def get_hyprmon_dir():
    return os.path.expanduser("~/.config/hyprmon")


def write_hyprmon_lua(monitors):
    hypr_dir = get_hypr_dir()
    os.makedirs(hypr_dir, exist_ok=True)
    lua_file = os.path.join(hypr_dir, "hyprmon.lua")

    lines = ["-- Generated by Quickshell DisplaysConfig (ii-DYNAMiC)"]
    for m in monitors:
        name = m.get("name")
        if not name or m.get("disabled") or not m.get("Active", True):
            continue
        w = m.get("PxW") or m.get("width")
        h = m.get("PxH") or m.get("height")
        hz = m.get("Hz") or m.get("refreshRate") or 60.0
        scale = m.get("Scale") or m.get("scale") or 1.0
        x = m.get("X") if m.get("X") is not None else m.get("x", 0)
        y = m.get("Y") if m.get("Y") is not None else m.get("y", 0)
        transform = m.get("Transform") if m.get("Transform") is not None else m.get("transform", 0)

        mode_str = f"{w}x{h}@{hz}" if w and h else "preferred"
        pos_str = f"{x}x{y}"
        lines.append(
            f'hl.monitor({{ output = "{name}", mode = "{mode_str}", position = "{pos_str}", scale = "{scale}" }})'
        )

    # Global fallback for unlisted monitors
    lines.append('hl.monitor({ output = "", mode = "preferred", position = "auto", scale = "1" })')

    with open(lua_file, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def write_monitors_conf(monitors):
    hypr_dir = get_hypr_dir()
    os.makedirs(hypr_dir, exist_ok=True)
    conf_file = os.path.join(hypr_dir, "monitors.conf")

    lines = [
        "# >>> hyprmon:begin >>> (auto-generated — do not edit between markers)",
    ]
    for m in monitors:
        name = m.get("name")
        if not name:
            continue
        if m.get("disabled") or not m.get("Active", True):
            lines.append(f"monitor={name},disable")
            continue
        w = m.get("PxW") or m.get("width")
        h = m.get("PxH") or m.get("height")
        hz = m.get("Hz") or m.get("refreshRate") or 60.0
        scale = m.get("Scale") or m.get("scale") or 1.0
        x = m.get("X") if m.get("X") is not None else m.get("x", 0)
        y = m.get("Y") if m.get("Y") is not None else m.get("y", 0)
        mode_str = f"{w}x{h}@{float(hz):.2f}" if w and h else "preferred"
        lines.append(f"monitor={name},{mode_str},{x}x{y},{scale}")

    lines.append("")
    lines.append("# Fallback for unknown monitors")
    lines.append("monitor=,preferred,auto,1")
    lines.append("# <<< hyprmon:end <<<")

    with open(conf_file, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def write_monitors_json(monitors):
    hypr_dir = get_hypr_dir()
    os.makedirs(hypr_dir, exist_ok=True)
    json_file = os.path.join(hypr_dir, "monitors.json")

    mon_map = {}
    for idx, m in enumerate(monitors):
        name = m.get("name")
        if not name:
            continue
        w = m.get("PxW") or m.get("width") or 1920
        h = m.get("PxH") or m.get("height") or 1080
        hz = m.get("Hz") or m.get("refreshRate") or 60.0
        scale = m.get("Scale") or m.get("scale") or 1.0
        x = m.get("X") if m.get("X") is not None else m.get("x", 0)
        y = m.get("Y") if m.get("Y") is not None else m.get("y", 0)
        transform = m.get("Transform") if m.get("Transform") is not None else m.get("transform", 0)

        mon_map[name] = {
            "resolution": f"{w}x{h}",
            "refresh_rate": float(hz),
            "scale": float(scale),
            "rotation": int(transform),
            "position_x": int(x),
            "position_y": int(y),
            "is_primary": (idx == 0)
        }

    data = {
        "workspaces": [
            {
                "name": "Default",
                "monitors": mon_map
            }
        ],
        "active_workspace": 0
    }

    with open(json_file, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)


def apply_monitors_live(monitors):
    for m in monitors:
        name = m.get("name")
        if not name or m.get("disabled") or not m.get("Active", True):
            continue
        w = m.get("PxW") or m.get("width")
        h = m.get("PxH") or m.get("height")
        hz = m.get("Hz") or m.get("refreshRate") or 60.0
        scale = m.get("Scale") or m.get("scale") or 1.0
        x = m.get("X") if m.get("X") is not None else m.get("x", 0)
        y = m.get("Y") if m.get("Y") is not None else m.get("y", 0)

        mode_str = f"{w}x{h}@{hz}" if w and h else "preferred"
        pos_str = f"{x}x{y}"
        cmd = f'hl.monitor({{ output = "{name}", mode = "{mode_str}", position = "{pos_str}", scale = "{scale}" }})'
        try:
            subprocess.run(["hyprctl", "eval", cmd], capture_output=True, timeout=2)
        except Exception as e:
            sys.stderr.write(f"Error applying monitor {name}: {e}\n")


def save_profile_file(profile_name, profile_dict):
    profiles_dir = os.path.join(get_hyprmon_dir(), "profiles")
    os.makedirs(profiles_dir, exist_ok=True)
    out_file = os.path.join(profiles_dir, f"{profile_name}.json")
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(profile_dict, f, indent=2)


def handle_profile_json(json_str, apply=False, save_profile=None):
    try:
        profile = json.loads(json_str)
    except Exception as e:
        sys.stderr.write(f"Error parsing profile JSON: {e}\n")
        return

    monitors = profile.get("monitors", [])
    if not monitors:
        return

    write_hyprmon_lua(monitors)
    write_monitors_conf(monitors)
    write_monitors_json(monitors)

    name = save_profile or profile.get("name") or "default"
    save_profile_file(name, profile)
    save_profile_file("__quickshell_live__", profile)

    if apply:
        apply_monitors_live(monitors)


def apply_profile(name):
    profiles_dir = os.path.join(get_hyprmon_dir(), "profiles")
    path = os.path.join(profiles_dir, f"{name}.json")
    if not os.path.exists(path):
        sys.stderr.write(f"Profile {name} not found at {path}\n")
        return
    with open(path, "r", encoding="utf-8") as f:
        handle_profile_json(f.read(), apply=True, save_profile=name)


def list_profiles():
    profiles_dir = os.path.join(get_hyprmon_dir(), "profiles")
    if not os.path.exists(profiles_dir):
        return
    for item in sorted(os.listdir(profiles_dir)):
        if item.endswith(".json") and item != "__quickshell_live__.json":
            print(item[:-5])


def update_monitor_config(file_path, monitor_name, res="preferred", pos="auto", scale="1", transform=None, vrr=None, mirror=None, disabled=False, is_primary=False):
    if not os.path.exists(file_path):
        with open(file_path, 'w') as f:
            f.write("# Hyprland Monitor Configuration\n")

    with open(file_path, 'r') as f:
        lines = f.readlines()

    original_content_lines = []
    pattern = re.compile(rf'^\s*monitor\s*=\s*{re.escape(monitor_name)}\s*,', re.IGNORECASE)
    
    for line in lines:
        if pattern.match(line):
            continue 
        original_content_lines.append(line)

    if disabled:
        monitor_line = f"monitor = {monitor_name}, disable\n"
    else:
        line_parts = [f"{monitor_name}", f"{res}", f"{pos}", f"{scale}"]
        if transform is not None: line_parts.append(f"transform,{transform}")
        if vrr is not None: line_parts.append(f"vrr,{vrr}")
        if mirror: line_parts.append(f"mirror,{mirror}")
        monitor_line = f"monitor = {', '.join(line_parts)}\n"

    if is_primary:
        new_lines = [monitor_line] + original_content_lines
    else:
        new_lines = original_content_lines + [monitor_line]

    with open(file_path, 'w') as f:
        f.writelines(new_lines)


def save_all_monitors(file_path, monitors_json):
    try:
        monitors = json.loads(monitors_json)
    except Exception as e:
        print(f"Error parsing JSON: {e}")
        return

    lines = ["# Hyprland Monitor Configuration\n", "# Generated by Quickshell SystemDisplay\n"]
    for m in monitors:
        name = m.get("name")
        if not name: continue
        res = m.get("res", "preferred")
        pos = m.get("pos", "auto")
        scale = m.get("scale", "1")
        transform = m.get("transform")
        vrr = m.get("vrr")
        mirror = m.get("mirror")
        disabled = m.get("disabled", False)

        if disabled:
            lines.append(f"monitor = {name}, disable\n")
        else:
            parts = [f"{name}", f"{res}", f"{pos}", f"{scale}"]
            if transform is not None: parts.append(f"transform,{transform}")
            if vrr is not None: parts.append(f"vrr,{vrr}")
            if mirror: parts.append(f"mirror,{mirror}")
            lines.append(f"monitor = {', '.join(parts)}\n")

    with open(file_path, 'w') as f:
        f.writelines(lines)
    print(f"Bulk updated {len(monitors)} monitors in {file_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Update Hyprland monitor configuration.")
    parser.add_argument("--file", default="~/.config/hypr/monitors.conf", help="Path to monitors.conf")
    parser.add_argument("--name", help="Monitor name (e.g., eDP-1)")
    parser.add_argument("--res", default="preferred", help="Resolution@Refresh")
    parser.add_argument("--pos", default="auto", help="Position")
    parser.add_argument("--scale", default="1", help="Scaling factor")
    parser.add_argument("--transform", type=int, help="Rotation")
    parser.add_argument("--vrr", type=int, help="VRR")
    parser.add_argument("--mirror", help="Monitor name to mirror")
    parser.add_argument("--primary", action="store_true", help="Set as primary")
    parser.add_argument("--disable", action="store_true", help="Disable monitor")
    parser.add_argument("--all", help="JSON string representing all monitors for bulk update")
    parser.add_argument("--profile-json", help="Profile JSON string to parse and apply")
    parser.add_argument("--save-profile", help="Profile name to save as")
    parser.add_argument("--apply-profile", help="Apply a saved profile by name")
    parser.add_argument("--list-profiles", action="store_true", help="List all saved profile names")
    parser.add_argument("--apply", action="store_true", help="Apply settings live to Hyprland")

    args = parser.parse_args()
    file_path = os.path.expanduser(args.file)

    if args.list_profiles:
        list_profiles()
    elif args.apply_profile:
        apply_profile(args.apply_profile)
    elif args.profile_json:
        handle_profile_json(args.profile_json, apply=args.apply, save_profile=args.save_profile)
    elif args.all:
        save_all_monitors(file_path, args.all)
    elif args.name:
        update_monitor_config(file_path, args.name, res=args.res, pos=args.pos, scale=args.scale, 
                            transform=args.transform, vrr=args.vrr, mirror=args.mirror, 
                            disabled=args.disable, is_primary=args.primary)
    else:
        parser.print_help()
